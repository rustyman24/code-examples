public class denstiy {
    static void main(String[] args) {
        // Step 1: Declare and set mass and volume
        double mass = 100;
        double volume = 100;

        // Step 2: Calculate density (Density = Mass / Volume)
        double density = mass / volume;

        // Step 3: Print the output in the requested format
        System.out.println("Mass = " + mass + " kg");
        System.out.println("Volume = " + volume + " metres cubed");
        System.out.println("Density = " + density + " kg per metre cubed");
    }
}
