public class Swap_numbers {
    static void main(String[] args) {
        int num1,num2,num3;

        num1 = 4;

        num2=5;

        System.out.println("num1 ="+num1);

        System.out.println("num2 ="+num2);

        num3=num1;

        num1=num2;

        System.out.println("num3 ="+num3);

        num1=num3;
        num2=num1;

        System.out.println("num1 ="+num1+"num2 ="+num2);

    }
}
